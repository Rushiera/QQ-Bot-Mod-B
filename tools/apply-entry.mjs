// apply-entry.mjs — 生成 QQBot mod B 的入口启动器（自研单体入口）
//
// 用法：node apply-entry.mjs [--dry]
// 做什么：写出项目根的两个入口文件——
//   启动QQBotB.bat   有窗口版（四步回显，排错用）
//   启动QQBotB.vbs   无窗口版（日常用；wscript 起，不留黑窗口）
// 语义：一键全流程重启——停旧实例 → 清业务面实例锁 → 落启动会话 → 起自研单体。
//       自研单体随后自己起 NapCat（无窗口）→ 连 OneBot → 拉起业务面 QQ Agent。
//
// 🔴 .bat / .vbs 写入铁律（判例 2026-10-10 · tools/patch-qqagent-cwd.mjs）：
//    两文件是 ASCII + CRLF，禁用会改编码 / 换行的通道写（cmd 按 GBK 解析、
//    WSH 按 ANSI 解析；BOM 或 LF 会让它们解析崩）。故入口文件只由本脚本生成——
//    片段按 LF 书写，落盘统一转 CRLF + 无 BOM，写后断言纯 ASCII。
//
// 边界：不动 NapCat（杀它要重新登录）· 不动业务面存档（messages / memory / sessions）。

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const DRY = process.argv.includes('--dry');

const BAT = String.raw`@echo off
rem ===========================================================================
rem QQBot mod B launcher (ONE-CLICK FULL RESTART) -- monolith entry
rem ===========================================================================
rem NOTE: keep this file ASCII-only + CRLF -- cmd parses .bat in GBK on Chinese
rem Windows; UTF-8 Chinese comments / LF endings break parsing.
rem Generated by tools\apply-entry.mjs -- do not hand-edit (regenerate instead).
rem
rem 2026-10-11: the entry moved from QQ Agent to the self-developed monolith
rem (app\). One click does:
rem   1) stop every running instance (QQ Agent.exe + our electron.exe)
rem   2) drop the stale QQ Agent instance lock (data\qq-agent.lock)
rem   3) open a startup session (launch == new session)
rem   4) start the monolith (tray resident, cwd pinned to app\)
rem The monolith then starts NapCat windowless, connects OneBot, and spawns
rem QQ Agent (business layer) once the protocol end is up.
rem
rem NOT touched on purpose:
rem   NapCat (runtime\NapCat\...\QQ.exe) -- killing it forces a re-login.
rem   data\messages\ chat archive / data\memory\ group notes / data\sessions\ runs
rem
rem The old QQAgent launcher still works (business layer only).

setlocal
set "ROOT=%~dp0"
set "APPDIR=%ROOT%app"
set "QQAGENT=%ROOT%_unpack"

echo [1/4] stopping running instances...
taskkill /IM "QQ Agent.exe" /T /F >nul 2>&1
powershell -NoProfile -Command "Get-Process electron -ErrorAction SilentlyContinue | Where-Object { $_.Path -like '*QQBotB*' } | Stop-Process -Force -ErrorAction SilentlyContinue" >nul 2>&1
rem wait a moment so the OS releases the lock file and the log handles
ping -n 3 127.0.0.1 >nul

echo [2/4] clearing QQ Agent instance lock...
if exist "%QQAGENT%\data\qq-agent.lock" del /f /q "%QQAGENT%\data\qq-agent.lock" >nul 2>&1

echo [3/4] opening startup session...
node "%ROOT%tools\open-startup-session.mjs"

echo [4/4] starting monolith...
rem [qqbotb-entry:cwd-pin] pin cwd to app\ -- never inherit the caller's cwd.
cd /d "%APPDIR%" || exit /b 1
start "" "%APPDIR%\node_modules\electron\dist\electron.exe" .
endlocal
`;

const VBS = String.raw`' QQBot mod B launcher (no console window) -- monolith entry
' NOTE: keep this file ASCII-only + CRLF (WSH parses .vbs as ANSI on Chinese Windows).
' Generated by tools\apply-entry.mjs -- do not hand-edit (regenerate instead).
' 1) stop running instances (QQ Agent.exe + our electron.exe under this folder)
' 2) drop the stale QQ Agent instance lock
' 3) open a startup session (launch == new session)
' 4) start the monolith -- it starts NapCat windowless, then spawns QQ Agent
' NapCat itself is NOT touched on purpose (killing it forces a re-login).

Set fso = CreateObject("Scripting.FileSystemObject")
Set sh = CreateObject("WScript.Shell")
root = fso.GetParentFolderName(WScript.ScriptFullName)
q = Chr(34)

sh.Run "cmd /c taskkill /IM " & q & "QQ Agent.exe" & q & " /T /F", 0, True
sh.Run "powershell -NoProfile -Command " & q & "Get-Process electron -ErrorAction SilentlyContinue | Where-Object { $_.Path -like '*QQBotB*' } | Stop-Process -Force -ErrorAction SilentlyContinue" & q, 0, True

lockFile = root & "\_unpack\data\qq-agent.lock"
If fso.FileExists(lockFile) Then fso.DeleteFile lockFile, True

sh.Run "node " & q & root & "\tools\open-startup-session.mjs" & q, 0, True

sh.CurrentDirectory = root & "\app"
sh.Run q & root & "\app\node_modules\electron\dist\electron.exe" & q & " .", 1, False
`;

/** 纯 ASCII 断言——非 ASCII 字节会破坏 cmd / WSH 解析。 */
function assertAscii(name, text) {
  const bad = [...text].findIndex((ch) => ch.charCodeAt(0) > 127);
  if (bad >= 0) throw new Error(`${name} 含非 ASCII 字节 @ ${bad}：${text.slice(bad, bad + 40)}`);
}

/** 落盘：LF 片段 → CRLF + 无 BOM。 */
function writeLauncher(file, text) {
  assertAscii(path.basename(file), text);
  const crlf = text.split('\n').join('\r\n');
  if (DRY) return { file, bytes: Buffer.byteLength(crlf, 'utf8'), dry: true };
  fs.writeFileSync(file, crlf, { encoding: 'utf8', flag: 'w' });
  const written = fs.readFileSync(file, 'utf8');
  assertAscii(path.basename(file), written);
  if (written.includes('\r\n') === false) throw new Error(`${path.basename(file)} 换行不是 CRLF`);
  return { file, bytes: Buffer.byteLength(written, 'utf8'), dry: false };
}

const results = [
  writeLauncher(path.join(ROOT, '启动QQBotB.bat'), BAT),
  writeLauncher(path.join(ROOT, '启动QQBotB.vbs'), VBS)
];

console.log(JSON.stringify({
  ok: true,
  dry: DRY,
  root: ROOT,
  files: results.map((item) => ({
    file: path.relative(ROOT, item.file),
    bytes: item.bytes,
    written: item.dry === false
  }))
}, null, 2));
